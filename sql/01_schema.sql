DROP SCHEMA IF EXISTS olx CASCADE;
CREATE SCHEMA olx;
SET search_path TO olx;

CREATE TABLE cities (
    city_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_name VARCHAR(50) NOT NULL UNIQUE,
    state VARCHAR(50) NOT NULL
);

CREATE TABLE categories (
    category_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR(50) NOT NULL UNIQUE,
    parent_id SMALLINT NULL REFERENCES categories (category_id) ON DELETE RESTRICT,
    CONSTRAINT chk_categories_no_self_parent CHECK (parent_id IS NULL OR parent_id <> category_id)
);

CREATE TABLE boost_packages (
    package_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    package_name VARCHAR(60) NOT NULL UNIQUE,
    price NUMERIC(10, 2) NOT NULL CONSTRAINT chk_boost_packages_price_positive CHECK (price > 0),
    duration_days SMALLINT NOT NULL CONSTRAINT chk_boost_packages_duration_positive CHECK (duration_days > 0)
);

CREATE TABLE users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(100) NOT NULL CONSTRAINT chk_users_name_nonempty CHECK (length(btrim(full_name)) > 0),
    phone VARCHAR(15) NOT NULL UNIQUE CONSTRAINT chk_users_phone_digits CHECK (phone ~ '^[0-9]{10}$'),
    email VARCHAR(255) NULL UNIQUE CONSTRAINT chk_users_email_format CHECK (email IS NULL OR email ~* '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
    city_id SMALLINT NOT NULL REFERENCES cities (city_id) ON DELETE RESTRICT,
    phone_verified BOOLEAN NOT NULL DEFAULT FALSE,
    is_banned BOOLEAN NOT NULL DEFAULT FALSE,
    joined_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE listings (
    listing_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id BIGINT NOT NULL REFERENCES users (user_id) ON DELETE RESTRICT,
    category_id SMALLINT NOT NULL REFERENCES categories (category_id) ON DELETE RESTRICT,
    title VARCHAR(150) NOT NULL CONSTRAINT chk_listings_title_nonempty CHECK (length(btrim(title)) > 0),
    description TEXT NULL,
    price NUMERIC(12, 2) NOT NULL CONSTRAINT chk_listings_price_positive CHECK (price > 0),
    is_negotiable BOOLEAN NOT NULL DEFAULT TRUE,
    item_condition VARCHAR(20) NOT NULL CONSTRAINT chk_listings_condition CHECK (item_condition IN ('NEW', 'LIKE_NEW', 'GOOD', 'FAIR')),
    attributes JSONB NOT NULL DEFAULT '{}'::jsonb CONSTRAINT chk_listings_attributes_object CHECK (jsonb_typeof(attributes) = 'object'),
    city_id SMALLINT NOT NULL REFERENCES cities (city_id) ON DELETE RESTRICT,
    locality VARCHAR(100) NOT NULL CONSTRAINT chk_listings_locality_nonempty CHECK (length(btrim(locality)) > 0),
    latitude NUMERIC(9, 6) NOT NULL CONSTRAINT chk_listings_latitude_range CHECK (latitude BETWEEN -90 AND 90),
    longitude NUMERIC(9, 6) NOT NULL CONSTRAINT chk_listings_longitude_range CHECK (longitude BETWEEN -180 AND 180),
    image_count SMALLINT NOT NULL DEFAULT 0 CONSTRAINT chk_listings_image_count_range CHECK (image_count BETWEEN 0 AND 20),
    view_count INTEGER NOT NULL DEFAULT 0 CONSTRAINT chk_listings_view_count_nonneg CHECK (view_count >= 0),
    boost_package_id SMALLINT NULL REFERENCES boost_packages (package_id) ON DELETE SET NULL,
    status VARCHAR(20) NOT NULL CONSTRAINT chk_listings_status CHECK (status IN ('ACTIVE', 'SOLD', 'EXPIRED', 'REMOVED')),
    posted_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    sold_at TIMESTAMPTZ NULL,
    CONSTRAINT chk_listings_expiry_after_post CHECK (expires_at > posted_at),
    CONSTRAINT chk_listings_sold_consistency CHECK (
        (status = 'SOLD' AND sold_at IS NOT NULL AND sold_at >= posted_at)
        OR (status <> 'SOLD' AND sold_at IS NULL)
    )
);

CREATE TABLE chat_threads (
    thread_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id BIGINT NOT NULL REFERENCES listings (listing_id) ON DELETE CASCADE,
    buyer_id BIGINT NOT NULL REFERENCES users (user_id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_chat_threads_listing_buyer UNIQUE (listing_id, buyer_id)
);

CREATE TABLE chat_messages (
    message_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    thread_id BIGINT NOT NULL REFERENCES chat_threads (thread_id) ON DELETE CASCADE,
    sender_id BIGINT NOT NULL REFERENCES users (user_id) ON DELETE RESTRICT,
    body TEXT NOT NULL CONSTRAINT chk_chat_messages_body_nonempty CHECK (length(btrim(body)) > 0),
    sent_at TIMESTAMPTZ NOT NULL,
    is_read BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE offers (
    offer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id BIGINT NOT NULL REFERENCES listings (listing_id) ON DELETE CASCADE,
    buyer_id BIGINT NOT NULL REFERENCES users (user_id) ON DELETE RESTRICT,
    offer_price NUMERIC(12, 2) NOT NULL CONSTRAINT chk_offers_price_positive CHECK (offer_price > 0),
    status VARCHAR(20) NOT NULL CONSTRAINT chk_offers_status CHECK (status IN ('PENDING', 'ACCEPTED', 'REJECTED', 'COUNTERED')),
    created_at TIMESTAMPTZ NOT NULL,
    responded_at TIMESTAMPTZ NULL,
    CONSTRAINT chk_offers_response_consistency CHECK (
        (status = 'PENDING' AND responded_at IS NULL)
        OR (status <> 'PENDING' AND responded_at IS NOT NULL AND responded_at >= created_at)
    )
);

CREATE TABLE favourites (
    user_id BIGINT NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    listing_id BIGINT NOT NULL REFERENCES listings (listing_id) ON DELETE CASCADE,
    saved_at TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (user_id, listing_id)
);

CREATE TABLE reports (
    report_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id BIGINT NOT NULL REFERENCES listings (listing_id) ON DELETE CASCADE,
    reporter_id BIGINT NOT NULL REFERENCES users (user_id) ON DELETE RESTRICT,
    reason VARCHAR(30) NOT NULL CONSTRAINT chk_reports_reason CHECK (reason IN ('FRAUD', 'SPAM', 'ALREADY_SOLD', 'WRONG_CATEGORY', 'OFFENSIVE')),
    created_at TIMESTAMPTZ NOT NULL,
    status VARCHAR(20) NOT NULL CONSTRAINT chk_reports_status CHECK (status IN ('OPEN', 'ACTIONED', 'DISMISSED')),
    CONSTRAINT uq_reports_listing_reporter UNIQUE (listing_id, reporter_id)
);

CREATE TABLE seller_ratings (
    rating_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id BIGINT NOT NULL REFERENCES users (user_id) ON DELETE RESTRICT,
    rater_id BIGINT NOT NULL REFERENCES users (user_id) ON DELETE RESTRICT,
    listing_id BIGINT NOT NULL REFERENCES listings (listing_id) ON DELETE CASCADE,
    stars SMALLINT NOT NULL CONSTRAINT chk_seller_ratings_stars_range CHECK (stars BETWEEN 1 AND 5),
    comment TEXT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_seller_ratings_listing_rater UNIQUE (listing_id, rater_id),
    CONSTRAINT chk_seller_ratings_not_self CHECK (seller_id <> rater_id)
);

